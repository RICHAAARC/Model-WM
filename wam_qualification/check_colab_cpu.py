"""Fresh Colab-like subprocess: actual Backend loaders, synthetic local checkpoints.

Only CUDA availability and device transfer are redirected. No model loader is
mocked; this checks serialization and imports, not real weights/CUDA compatibility.
"""
import json
import os
import subprocess
import sys
import tempfile
import time
import traceback
from pathlib import Path
from unittest.mock import patch


def child(source, output):
    import torch
    import matplotlib
    from diffusers import (AutoencoderKL, UNet2DConditionModel, DDIMScheduler,
        StableDiffusionPipeline, DPMSolverMultistepScheduler, DiffusionPipeline)
    from transformers import CLIPTextConfig, CLIPTextModel, CLIPTokenizer, CLIPImageProcessor
    from .backend import Backend
    from .environment import check
    from .check_official_cpu import check as official_check
    receipt=check()
    negative_controls=[]
    assert matplotlib.get_backend().lower()=="agg"
    torch.set_num_threads(1)
    with tempfile.TemporaryDirectory(prefix="wam-synthetic-load-") as d:
        d=Path(d)
        # Capture the synthetic exact official WAM state generated by the existing
        # architecture/interface check, while still performing real serialization.
        saved=[]
        real_save=torch.save
        def save_and_capture(obj, target, *args, **kwargs):
            real_save(obj,target,*args,**kwargs)
            if Path(target).name=="synthetic-state.pth":
                real_save(obj,d/"wam-synthetic.pth");saved.append(True)
        with patch.object(torch,"save",save_and_capture):
            official=official_check(source)
        assert saved==[True]
        # Tiny SD components test the actual pinned from_pretrained implementation.
        # Their random tensors are fixtures, never candidate experiment weights.
        (d/"vocab.json").write_text(json.dumps({"<|startoftext|>":0,"<|endoftext|>":1,"a</w>":2}))
        (d/"merges.txt").write_text("#version: 0.2\n")
        tokenizer=CLIPTokenizer(vocab_file=str(d/"vocab.json"),merges_file=str(d/"merges.txt"),model_max_length=77)
        text=CLIPTextModel(CLIPTextConfig(vocab_size=3,hidden_size=32,intermediate_size=64,
            num_hidden_layers=1,num_attention_heads=4,max_position_embeddings=77))
        vae=AutoencoderKL(in_channels=3,out_channels=3,down_block_types=("DownEncoderBlock2D",),
            up_block_types=("UpDecoderBlock2D",),block_out_channels=(32,),latent_channels=4,norm_num_groups=8,sample_size=32)
        unet=UNet2DConditionModel(sample_size=32,in_channels=4,out_channels=4,layers_per_block=1,
            block_out_channels=(32,64),down_block_types=("CrossAttnDownBlock2D","DownBlock2D"),
            up_block_types=("UpBlock2D","CrossAttnUpBlock2D"),cross_attention_dim=32,norm_num_groups=8,attention_head_dim=4)
        pipe=StableDiffusionPipeline(vae=vae,text_encoder=text,tokenizer=tokenizer,unet=unet,
            scheduler=DDIMScheduler(steps_offset=1,clip_sample=False),safety_checker=None,feature_extractor=None,requires_safety_checker=False)
        pipe.save_pretrained(d/"base")
        del pipe,vae,unet,text
        # Keep the actual production component index, not the synthetic pipeline's
        # reduced optional-component list. No real tensor checkpoint is involved.
        import shutil
        fixtures=Path(__file__).with_name("fixtures")/"sd15"
        shutil.copyfile(fixtures/"model_index.json",d/"base/model_index.json")
        (d/"base/feature_extractor").mkdir()
        config=d/"base/feature_extractor/preprocessor_config.json"
        shutil.copyfile(fixtures/"feature_extractor/preprocessor_config.json",config)
        from .setup import component_preflight
        # Negative controls exercise both the metadata preflight and the real
        # pinned pipeline loader that failed in invocation 0003.
        config.rename(config.with_suffix(".held"))
        try:
            try:component_preflight(d/"base")
            except RuntimeError as exc:
                assert "preprocessor_config.json" in str(exc)
                negative_controls.append(dict(check="component_preflight",expected_failure=True,traceback=traceback.format_exc()))
            else:raise AssertionError("Missing processor config was admitted")
            try:StableDiffusionPipeline.from_pretrained(str(d/"base"),local_files_only=True,
                    torch_dtype=torch.float32,safety_checker=None,requires_safety_checker=False)
            except OSError as exc:
                assert "preprocessor_config.json" in str(exc)
                negative_controls.append(dict(check="real_pipeline_loader",expected_failure=True,traceback=traceback.format_exc()))
            else:raise AssertionError("Real loader did not reproduce the missing-config failure")
        finally:config.with_suffix(".held").rename(config)
        component_preflight(d/"base")
        # Continue through actual asset preparation and Drive-to-content routing.
        import shutil
        import tarfile
        from .setup import models, BASE_FILES
        from .core import save
        manifest=json.loads(Path(__file__).with_name("manifest.json").read_text())
        root=d/"receipts";root.mkdir()
        scratch=d/"content/runtime";scratch.mkdir(parents=True)
        drive=d/"drive-cache";drive.mkdir()
        new=d/"content/new";new.mkdir()
        paid=d/"content/paid"
        save(root/"manifest.json",manifest)
        save(root/"local_storage.json",dict(mappings=[dict(new=str(new),drive=str(drive),paid=str(paid))]))
        archive=drive/"wam/official_source.tar.gz";archive.parent.mkdir()
        with tarfile.open(archive,"w:gz") as tf:
            for p in Path(source).resolve().rglob("*"):
                if p.is_file() and (p.suffix in (".py",".json",".yaml",".txt",".md") or p.name=="LICENSE"):
                    tf.add(p,arcname="official/"+str(p.relative_to(Path(source).resolve())))
        save(archive.with_name(archive.name+".complete.json"),dict(url=f"https://codeload.github.com/facebookresearch/watermark-anything/tar.gz/{manifest['source_commit']}"))
        shutil.copyfile(d/"wam-synthetic.pth",drive/"wam/wam_mit.pth")
        save(drive/"wam/wam_mit.pth.complete.json",dict(url=manifest["checkpoint_url"]))
        for name in BASE_FILES:
            target=drive/"aqua/assets/base"/name;target.parent.mkdir(parents=True,exist_ok=True)
            shutil.copyfile(d/"base"/name,target)
            save(target.with_name(target.name+".complete.json"),dict(url=f"https://huggingface.co/{manifest['base_repo']}/resolve/{manifest['base_revision']}/{name}"))
        from .transport import preflight
        with patch("urllib.request.urlopen",side_effect=AssertionError("All synthetic assets are paid local fixtures")):
            preflight(root,new/"aqua",new/"wam")
            models(root,scratch,new/"aqua",new/"wam")
        paths=json.loads((root/"model_paths.json").read_text())
        assert Path(paths["checkpoint"]).is_relative_to(d/"content")
        assert all(p.resolve().is_relative_to(d/"content") for p in Path(paths["base"]).rglob("*") if p.is_file())
        assert not any(p.is_file() for p in new.rglob("*"))
        original_module_to=torch.nn.Module.to
        original_pipeline_to=DiffusionPipeline.to
        redirected=[]
        def cpu_transfer(original, obj, *args, **kwargs):
            args=list(args)
            if args and str(args[0])=="cuda":
                args[0]="cpu";redirected.append(type(obj).__name__)
            if str(kwargs.get("device"))=="cuda":
                kwargs["device"]="cpu";redirected.append(type(obj).__name__)
            return original(obj,*args,**kwargs)
        with patch.object(torch.cuda,"is_available",return_value=True), \
             patch.object(torch.nn.Module,"to",lambda obj,*a,**k:cpu_transfer(original_module_to,obj,*a,**k)), \
             patch.object(DiffusionPipeline,"to",lambda obj,*a,**k:cpu_transfer(original_pipeline_to,obj,*a,**k)):
            backend=Backend(manifest,**paths)
        assert isinstance(backend.pipe.scheduler,DPMSolverMultistepScheduler)
        assert next(backend.wam.parameters()).device.type=="cpu"
        assert next(backend.pipe.unet.parameters()).device.type=="cpu"
        assert backend.pipe.unet.dtype==torch.float32 and backend.pipe.safety_checker is None
        assert isinstance(backend.pipe.feature_extractor,CLIPImageProcessor)
        assert {"Wam","StableDiffusionPipeline"} <= set(redirected)
        transformed=backend.transform(__import__("PIL.Image",fromlist=["Image"]).new("RGB",(512,512)))
        assert tuple(transformed.shape)==(3,512,512)
    receipt.update(status="FULL_CPU_SYNTHETIC_LOADING_PASSED",official_checks=official["checks"],
        negative_controls=negative_controls,
        checks=["fresh Colab inline environment sanitized by Supervisor", "actual strict torch.load synthetic WAM",
            "actual StableDiffusionPipeline save/from_pretrained local-only", "actual Backend initialization",
            "DPM scheduler conversion", "FP32 and safety settings", "official image transform",
            "actual asset preflight and models preparation", "paid Drive fixtures restored only under content",
            "fixed official model_index and preprocessing config", "missing-config negative controls in preflight and real loader",
            "real CLIPImageProcessor loaded without disabling the component"],
        device_transfer_redirected_to_cpu=redirected,real_weights_loaded=False,gpu_started=False,
        scientific_pass=None,limitation="Synthetic WAM plus tiny SD serialization; real checkpoints and CUDA remain user-run only")
    Path(output).write_text(json.dumps(receipt,indent=2)+"\n")


def main(source, output):
    from .entry import Supervisor, PACKAGE
    manifest=json.loads((PACKAGE/"manifest.json").read_text())
    with tempfile.TemporaryDirectory() as d, patch.dict(os.environ,{"MPLBACKEND":"module://matplotlib_inline.backend_inline"}):
        supervisor=Supervisor(Path(d),manifest,manifest["inherited_resources"],time.time(),0,Path(d))
        supervisor.env["CUDA_VISIBLE_DEVICES"]=""
        supervisor.env["HF_HOME"]=str(Path(d)/"empty-hf-cache")
        result=subprocess.run([sys.executable,"-m","wam_qualification.check_colab_cpu","--child",source,output],
            env=supervisor.env,check=True)
        assert os.environ["MPLBACKEND"]=="module://matplotlib_inline.backend_inline"
    print("FULL_CPU_SYNTHETIC_LOADING_PASSED")


if __name__=="__main__":
    child(*sys.argv[2:4]) if sys.argv[1]=="--child" else main(*sys.argv[1:3])
